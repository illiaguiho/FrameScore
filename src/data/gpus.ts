// Relative GPU performance, scaled so GeForce GTX 1060 6GB = 100.
// Numbers are hand-tuned approximations of typical 1080p gaming performance,
// not measurements. `msrp` (USD launch price) marks cards that are still sold
// and is used for upgrade suggestions.

export type GpuKind = "desktop" | "laptop" | "integrated";
export type Brand = "nvidia" | "amd" | "intel" | "valve";

export interface Gpu {
  id: string;
  name: string;
  brand: Brand;
  score: number;
  vram: number; // GB, 0 = shares system memory
  kind: GpuKind;
  msrp?: number;
}

type Row = [model: string, score: number, vram: number, kind?: GpuKind, msrp?: number];

const make = (brand: Brand, prefix: string, rows: Row[]): Gpu[] =>
  rows.map(([model, score, vram, kind = "desktop", msrp]) => {
    const name = `${prefix} ${model}`;
    return {
      id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
      name,
      brand,
      score,
      vram,
      kind,
      msrp,
    };
  });

