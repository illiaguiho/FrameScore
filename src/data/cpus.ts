// Relative CPU gaming performance, scaled so Core i5-4590 = 100.
// Hand-tuned approximations blending single-thread speed and core count.

import type { Brand } from "./gpus";

export interface Cpu {
  id: string;
  name: string;
  brand: Brand;
  score: number;
  laptop: boolean;
  msrp?: number;
}

type Row = [model: string, score: number, laptop?: boolean, msrp?: number];

const make = (brand: Brand, prefix: string, rows: Row[]): Cpu[] =>
  rows.map(([model, score, laptop = false, msrp]) => {
    const name = `${prefix} ${model}`;
    return {
      id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
      name,
      brand,
      score,
      laptop,
      msrp,
    };
  });

